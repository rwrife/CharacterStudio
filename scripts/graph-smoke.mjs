import { _electron as electron, expect } from '@playwright/test'
import { mkdir, readFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import assert from 'node:assert/strict'

const output = resolve('artifacts', 'desktop-smoke')
await mkdir(output, { recursive: true })
const packaged = process.argv.includes('--packaged')
const app = await electron.launch({
  ...(packaged ? { executablePath: resolve('release', 'KimodoStudio-win32-arm64', 'KimodoStudio.exe'), args: [] } : { args: ['.'] }),
  env: { ...process.env, STUDIO_DATA_DIR: resolve('artifacts', 'validation-state') }, timeout: 60000
})
try {
  const page = await app.firstWindow(), errors = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('console', e => { if (e.type() === 'error') errors.push(e.text()) })
  await page.getByRole('heading', { name: 'Character lab' }).waitFor()
  await page.getByRole('button', { name: 'Motion library & batches' }).click()
  await page.getByRole('button', { name: 'Fighting graph template' }).click()
  await expect(page.locator('.react-flow__node')).toHaveCount(3)
  await expect(page.locator('.react-flow__edge')).toHaveCount(3)
  const punch = page.locator('.react-flow__node').filter({ hasText: 'Right hook' })
  await punch.click()
  await expect(page.getByLabel('Incoming context for Right hook')).toHaveValue(/.+/)
  const options = await page.getByLabel('Incoming context for Right hook').locator('option').allTextContents()
  assert.deepEqual(options, ['Fighting idle → Right hook', 'Fighting idle → Low crouch → Right hook'])
  await page.getByLabel('Incoming context for Right hook').selectOption({ label: options[1] })
  await expect(page.locator('.context-inspector')).toContainText('Crouched down low in a fighting stance')
  await page.getByText('Effective model instructions', { exact: true }).click()
  await expect(page.locator('.effective-prompt')).toContainText('Throw a right hook punch')
  await expect(page.locator('.effective-prompt')).toContainText('Crouched down low')
  await page.getByRole('button', { name: 'Save graph', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Graph saved' }).waitFor()
  let state = await page.evaluate(() => window.studio.snapshot())
  const planId = state.plans[0].id, punchId = state.plans[0].nodes.find(n => n.label === 'Right hook').id
  const initialPosition = state.plans[0].nodes.find(n => n.id === punchId).position
  const box = await punch.boundingBox()
  assert.ok(box)
  await page.mouse.move(box.x + box.width / 2, box.y + 35)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 - 30, box.y + 95, { steps: 10 })
  await page.mouse.up()
  await page.getByRole('button', { name: 'Save graph', exact: true }).click()
  await expect.poll(async () => (await page.evaluate(() => window.studio.snapshot())).plans.find(p => p.id === planId).nodes.find(n => n.id === punchId).position.y).not.toBe(initialPosition.y)
  state = await page.evaluate(() => window.studio.snapshot())
  const plan = state.plans.find(p => p.id === planId)
  const edge = plan.edges.find(e => e.target === punchId)
  await page.locator(`.react-flow__edge[data-id="${edge.id}"] .react-flow__edge-interaction`).click({ force: true })
  await page.getByLabel('Transition seconds').fill('1')
  await page.getByRole('button', { name: 'Save graph', exact: true }).click()
  await expect.poll(async () => (await page.evaluate(() => window.studio.snapshot())).plans.find(p => p.id === planId).edges.find(e => e.id === edge.id).seconds).toBe(1)
  await page.getByRole('button', { name: 'Remove connection' }).click()
  await expect(page.locator('.react-flow__edge')).toHaveCount(2)
  const idle = page.locator('.react-flow__node').filter({ hasText: 'Fighting idle' })
  const source = await idle.locator('.react-flow__handle-right').boundingBox()
  const target = await punch.locator('.react-flow__handle-left').boundingBox()
  assert.ok(source && target)
  await page.mouse.move(source.x + source.width / 2, source.y + source.height / 2)
  await page.mouse.down()
  await page.mouse.move(target.x + target.width / 2, target.y + target.height / 2, { steps: 12 })
  await page.mouse.up()
  await expect(page.locator('.react-flow__edge')).toHaveCount(3)
  await punch.click()
  await page.getByLabel('Outgoing stance').fill('Standing upright after rising')
  await page.getByLabel('Outgoing stance').fill('')
  await page.getByLabel('Incoming context for Right hook').selectOption({ label: options[1] })
  await page.getByRole('button', { name: 'Save graph', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Graph saved' }).waitFor()
  const file = resolve('artifacts', 'graph-roundtrip.json')
  await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }) }, file)
  await page.getByRole('button', { name: 'Export configuration JSON' }).click()
  await page.getByRole('status').filter({ hasText: 'Configuration saved to' }).waitFor()
  const exported = JSON.parse(await readFile(file, 'utf8'))
  assert.equal(exported.schemaVersion, 2)
  assert.equal(exported.plan.nodes.filter(n => n.label === 'Right hook').length, 1)
  assert.equal(exported.plan.edges.filter(e => e.target === punchId).length, 2)
  await page.getByRole('dialog').evaluate(el => { el.scrollTop = 0 })
  await page.screenshot({ path: resolve(output, packaged ? 'packaged-animation-graph.png' : 'animation-graph.png') })
  await app.evaluate(({ BrowserWindow }) => { BrowserWindow.getAllWindows()[0].setSize(1100, 760) })
  assert.ok(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'Graph layout must fit minimum window width.')
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByRole('button', { name: 'Motion library & batches' }).click()
  await expect(page.locator('.react-flow__node')).toHaveCount(3)
  const restored = await page.evaluate(() => window.studio.snapshot())
  assert.deepEqual(restored.plans.find(p => p.id === planId), exported.plan)
  assert.deepEqual(errors, [])
  console.log(`${packaged ? 'Packaged' : 'Built'} graph editor: shared action contexts, native node dragging, handle connections, edge duration, JSON v2 round-trip, persisted layout and responsive UI passed.`)
} finally { await app.close() }
